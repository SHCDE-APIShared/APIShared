        private readonly IntPtr module;
        internal AiMilitaryNativeBindings(IntPtr module, ReadOnlySpan<byte> image, string hash)
        {
            if (module == IntPtr.Zero || !string.Equals(hash, ReferenceHash, StringComparison.OrdinalIgnoreCase))
                throw new InvalidOperationException("AI military layouts require the audited native image.");
            foreach (var entry in Entries)
            {
                if (entry.Rva < 0 || entry.Rva > image.Length - entry.Bytes.Length)
                    throw new InvalidOperationException("AI military function is outside the native image.");
                for (int i = 0; i < entry.Bytes.Length; i++)
                    if (image[entry.Rva + i] != entry.Bytes[i])
                        throw new InvalidOperationException("AI military native contract differs at RVA 0x" + entry.Rva.ToString("X"));
            }
            this.module = module;
        }
        internal T Bind<T>(int rva) where T : Delegate
        {
            foreach (var entry in Entries) if (entry.Rva == rva) return Marshal.GetDelegateForFunctionPointer<T>(module + rva);
            throw new InvalidOperationException("The native call has no validated AI military contract.");
        }
        internal static NativeSiteSpan[] CallOnlySpans()
        {
            var result = new NativeSiteSpan[Entries.Length];
            for (int i = 0; i < result.Length; i++) result[i] = new NativeSiteSpan(Entries[i].Rva, 1, NativeSiteMode.CallOnly);
            return result;
        }
